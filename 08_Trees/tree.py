# A tree is a data structure made of nodes connected by edges.
#
# A tree starts with one top node called the root.
#
# Example:
#
#              A
#            /   \
#           B     C
#          / \     \
#         D   E     F
#
# A = root
# B and C = children of A
# A = parent of B and C
# D, E, and F = leaf nodes
#