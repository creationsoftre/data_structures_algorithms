# ============================================================
# Binary Tree Basics
# ============================================================
#
# A binary tree is a tree where each node has at most two children.
#
# The two children are usually called:
#
#   left child
#   right child
#
# Example:
#
#              A
#            /   \
#           B     C
#          / \     \
#         D   E     F
#
# A is the root.
# B is A's left child.
# C is A's right child.
# D and E are children of B.
# F is the right child of C.
#