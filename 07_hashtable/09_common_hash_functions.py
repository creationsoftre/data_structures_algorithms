# ============================================================
# Common Hash Functions
# ============================================================
#
# A hash function converts a key into a number.
#
# That number is then used to find an index in a hash table.
#
# Simple idea:
#
#   key -> hash function -> index
#
# Different key types need different hash functions.
#
# Examples:
#
#   Integer key:
#       1023
#
#   String key:
#       "CAT"
#
#   Username key:
#       "trevonte"
#