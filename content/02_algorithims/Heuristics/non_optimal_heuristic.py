# ------------------------------------------------------------
# Non-optimal heuristic search
# ------------------------------------------------------------
#
# This search uses a heuristic to make a smart guess.
#
# It does not guarantee the best path.
#
# It only chooses the move that looks best right now based on
# the heuristic score.
#
# In this example, the heuristic is:
#
#   distance to the target
#
# A lower score means the position looks closer to the target.
# ------------------------------------------------------------